window.tfLang = function () {
  return sessionStorage.getItem("tf-lang") || "fr";
};

window.t = function (key) {
  const pack = window.TF_I18N[window.tfLang()] || window.TF_I18N.fr;
  return pack[key] || window.TF_I18N.fr[key] || key;
};

window.applyI18n = function () {
  const lang = window.tfLang();
  document.documentElement.lang = lang === "ar" ? "ar" : lang === "en" ? "en" : "fr";
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = window.t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-lang]").forEach((node) => {
    node.classList.toggle("on", node.dataset.lang === lang);
  });
  const area = document.querySelector(".nav-link.active");
  const crumb = document.querySelector("#crumb-area");
  if (area && crumb) crumb.textContent = window.t(area.dataset.areaKey);
};
